def _signed_block(response: ChatResponse) -> tuple[ThinkingBlock | None, int]:
    """The first signed reasoning block and its position in the turn."""
    for index, block in enumerate(response.thinking):
        if not block.redacted and block.signature:
            return block, index
    return None, -1


def _describe(response: ChatResponse, block: ThinkingBlock | None) -> dict[str, Any]:
    """Structural facts about the block, with the signature itself withheld.

    A signature is an opaque attestation over someone's inference; its shape is
    what identifies a scheme, and reports travel further than the runs that
    produced them, so only the length, the character classes and a truncated
    digest are recorded.
    """
    signature = block.signature if block is not None else None
    return {
        "thinking_blocks": len(response.thinking),
        "redacted_blocks": sum(1 for item in response.thinking if item.redacted),
        "thinking_chars": len(block.text) if block is not None else 0,
        "reasoning_tokens": response.usage.reasoning_tokens,
        "signature_present": signature is not None,
        "signature_length": len(signature) if signature else 0,
        "signature_alphabet": _alphabet(signature) if signature else None,
        "signature_sha256_prefix": (
            hashlib.sha256(signature.encode("utf-8")).hexdigest()[:16] if signature else None
        ),
        "finish_reason": response.finish_reason.value,
    }


def _alphabet(signature: str) -> str:
    """Name the character set a signature is drawn from."""
    characters = set(signature)
    if characters <= set(_BASE64 + "="):
        return "base64"
    if characters <= set(string.ascii_letters + string.digits + "-_="):
        return "base64url"
    if characters <= set(string.hexdigits):
        return "hex"
    return "other"
