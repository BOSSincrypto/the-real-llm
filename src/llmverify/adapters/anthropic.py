def _content_blocks(content: str | tuple[ContentPart, ...]) -> list[dict[str, Any]]:
    """Render message content as Anthropic content blocks."""
    if isinstance(content, str):
        return [{"type": "text", "text": content}] if content else []

    blocks: list[dict[str, Any]] = []
    for part in content:
        if isinstance(part, TextPart):
            if part.text:
                blocks.append({"type": "text", "text": part.text})
        elif isinstance(part, ImagePart):
            blocks.append(
                {
                    "type": "image",
                    "source": {
                        "type": "base64",
                        "media_type": part.media_type,
                        "data": base64.b64encode(part.data).decode("ascii"),
                    },
                }
            )
    return blocks


def _assistant_blocks(message: Message) -> list[dict[str, Any]]:
    """Render an assistant turn: reasoning first, then prose, then tool calls.

    The ordering is not cosmetic. Anthropic requires replayed thinking blocks to
    lead the turn, and a signature is only accepted in the position and form the
    API emitted it, so this function is what makes the thinking-signature probe
    a valid test rather than a source of false accusations.
    """
    blocks: list[dict[str, Any]] = []
    for block in message.thinking:
        if block.redacted:
            # A redacted block's payload is an opaque ``data`` string. It has no
            # dedicated slot on ThinkingBlock, so it is carried in ``text`` and
            # restored here; that keeps replay byte-exact, which is the only
            # thing that matters for it.
            blocks.append({"type": "redacted_thinking", "data": block.text})
        else:
            thinking: dict[str, Any] = {"type": "thinking", "thinking": block.text}
            if block.signature is not None:
                thinking["signature"] = block.signature
            blocks.append(thinking)

    blocks.extend(_content_blocks(message.content))

    for call in message.tool_calls:
        blocks.append(
            {
                "type": "tool_use",
                "id": call.id,
                "name": call.name,
                "input": call.arguments if call.arguments is not None else {},
            }
        )
    return blocks


def _tool_result_block(message: Message) -> dict[str, Any]:
    return {
        "type": "tool_result",
        "tool_use_id": message.tool_call_id or "",
        "content": message.text,
    }


# --------------------------------------------------------------------------- #
# Response parsing
# --------------------------------------------------------------------------- #


def _split_blocks(
    content: Any,
) -> tuple[str, tuple[ToolCall, ...], tuple[ThinkingBlock, ...]]:
    """Fold a content-block list into text, tool calls and reasoning blocks."""
    if not isinstance(content, list):
        return "", (), ()

    chunks: list[str] = []
    calls: list[ToolCall] = []
    thinking: list[ThinkingBlock] = []

    for block in content:
        if not isinstance(block, dict):
            continue
        kind = block.get("type")
        if kind == "text":
            text = block.get("text")
            if isinstance(text, str):
                chunks.append(text)
        elif kind == "tool_use":
            arguments = block.get("input")
            arguments = arguments if isinstance(arguments, dict) else None
            calls.append(
                ToolCall(
                    id=str(block.get("id") or ""),
                    name=str(block.get("name") or ""),
                    arguments_raw=json.dumps(
                        arguments if arguments is not None else block.get("input"),
                        ensure_ascii=False,
                    ),
                    arguments=arguments,
                )
            )
        elif kind == "thinking":
            signature = block.get("signature")
            thinking.append(
                ThinkingBlock(
                    text=block.get("thinking") if isinstance(block.get("thinking"), str) else "",
                    # Preserved verbatim: the whole point of the signature is
                    # that only the issuing endpoint can validate it, so any
                    # normalisation here would be tampering.
                    signature=signature if isinstance(signature, str) else None,
                )
            )
        elif kind == "redacted_thinking":
            data = block.get("data")
            thinking.append(
                ThinkingBlock(text=data if isinstance(data, str) else "", redacted=True)
            )

    return "".join(chunks), tuple(calls), tuple(thinking)


def _parse_usage(value: Any) -> Usage:
    """Map Anthropic's usage object, keeping its shape verbatim in ``raw``.

    The key names are a family signature in themselves: no other protocol
    spells cache accounting ``cache_read_input_tokens`` /
    ``cache_creation_input_tokens``.
    """
    if not isinstance(value, dict):
        return Usage()

    details = value.get("output_tokens_details")
    return Usage(
        input_tokens=_as_int(value.get("input_tokens")),
        output_tokens=_as_int(value.get("output_tokens")),
        reasoning_tokens=(
            _as_int(details.get("thinking_tokens")) if isinstance(details, dict) else None
        ),
        cache_read_tokens=_as_int(value.get("cache_read_input_tokens")),
        cache_write_tokens=_as_int(value.get("cache_creation_input_tokens")),
        raw=dict(value),
    )


def _stop_reason(value: Any) -> FinishReason:
    if not isinstance(value, str):
        return FinishReason.OTHER
    return _STOP_REASONS.get(value.strip().lower(), FinishReason.OTHER)


# --------------------------------------------------------------------------- #
# Stream assembly
# --------------------------------------------------------------------------- #


def _block_index(event: dict[str, Any], order: list[int], *, starting: bool = False) -> int:
    """Index of the content block an event refers to.

    Anthropic always sends ``index``. The fallback matters only for a proxy that
    forgets it, and it has to distinguish the two cases: a block that is opening
    gets a fresh slot, while a delta belongs to the block most recently opened.
    Getting that wrong would collapse a whole stream onto block zero.
    """
    index = event.get("index")
    if not isinstance(index, bool) and isinstance(index, int):
        return index
    if starting:
        return max(order) + 1 if order else 0
    return order[-1] if order else 0


def _new_block(start: dict[str, Any]) -> dict[str, Any]:
    return {
        "type": start.get("type"),
        "id": start.get("id"),
        "name": start.get("name"),
        "data": start.get("data"),
        "input": start.get("input"),
        "text": [start["text"]] if isinstance(start.get("text"), str) and start["text"] else [],
        "thinking": (
            [start["thinking"]]
            if isinstance(start.get("thinking"), str) and start["thinking"]
            else []
        ),
        "signature": (
            [start["signature"]]
            if isinstance(start.get("signature"), str) and start["signature"]
            else []
        ),
        "json": [],
    }


def _apply_delta(block: dict[str, Any], delta: Any) -> None:
    """Fold one ``content_block_delta`` into its accumulator."""
    if not isinstance(delta, dict):
        return
    kind = delta.get("type")
    if kind == "text_delta" and isinstance(delta.get("text"), str):
        block["text"].append(delta["text"])
    elif kind == "thinking_delta" and isinstance(delta.get("thinking"), str):
        block["thinking"].append(delta["thinking"])
    elif kind == "signature_delta" and isinstance(delta.get("signature"), str):
        block["signature"].append(delta["signature"])
    elif kind == "input_json_delta" and isinstance(delta.get("partial_json"), str):
        block["json"].append(delta["partial_json"])


def _finish_block(block: dict[str, Any]) -> dict[str, Any]:
    """Turn an accumulator back into the content block a single response holds."""
    kind = block.get("type")
    if kind == "thinking":
        out: dict[str, Any] = {"type": "thinking", "thinking": "".join(block["thinking"])}
        signature = "".join(block["signature"])
        if signature:
            out["signature"] = signature
        return out
    if kind == "redacted_thinking":
        return {"type": "redacted_thinking", "data": block.get("data") or ""}
    if kind == "tool_use":
        raw_json = "".join(block["json"])
        arguments = block.get("input") if isinstance(block.get("input"), dict) else {}
        if raw_json:
            try:
                parsed = json.loads(raw_json)
            except ValueError:
                # Keeping the unparseable fragment is the honest record: whether
                # a stack emits valid JSON is itself a fingerprint.
                parsed = None
            arguments = parsed if isinstance(parsed, dict) else arguments
        return {
            "type": "tool_use",
            "id": block.get("id") or "",
            "name": block.get("name") or "",
            "input": arguments,
        }
    return {"type": "text", "text": "".join(block["text"])}


# --------------------------------------------------------------------------- #
# Scalars
# --------------------------------------------------------------------------- #


def _as_str(value: Any) -> str | None:
    return value if isinstance(value, str) else None


def _as_int(value: Any) -> int | None:
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value
    if isinstance(value, float) and value.is_integer():
        return int(value)
    return None
