"""The Anthropic Messages protocol.

Anthropic's wire format differs from the OpenAI-compatible one in ways that are
themselves evidence, and this adapter is written to preserve every one of them.

**The system prompt is not a message.** It is a separate top-level ``system``
field. An endpoint that accepts a ``system`` *role* inside ``messages`` is not
running Anthropic's validator.

**Content is always a list of typed blocks**, so a single assistant turn can
carry reasoning, prose and tool calls at once and in a defined order.

**Reasoning blocks carry a cryptographic signature.** Anthropic's documentation
states that the signature exists so the API can verify that a thinking block was
generated by Claude, and that tampering with one produces a 400. That makes
signature round-tripping the single strongest identity check available for the
Claude family: a reseller that does not actually route through Anthropic cannot
produce a block that survives replay. It also means the replay must be built
*exactly* right -- a malformed replay would be rejected by a genuine endpoint
and read as a forgery, which is the worst failure mode this tool has.

**There is no ``seed`` and no ``logprobs``.** Those fields do not exist in this
protocol, so this adapter never sends them of its own accord. The api-surface
probe sends them deliberately through ``extra_body`` precisely to see whether
the endpoint quietly accepts fields a genuine Anthropic endpoint would reject.
"""

from __future__ import annotations

import base64
import json
from typing import Any, ClassVar

from ..errors import UnsupportedCapability
from ..types import (
    ApiFamily,
    ChatRequest,
    ChatResponse,
    ContentPart,
    FinishReason,
    ImagePart,
    Message,
    Role,
    TextPart,
    ThinkingBlock,
    Timing,
    ToolCall,
    ToolSpec,
    Usage,
)
from ._http import HttpResult, raise_for_status
from .base import Adapter, Capabilities, register_adapter

__all__ = ["AnthropicAdapter"]

_STOP_REASONS: dict[str, FinishReason] = {
    "end_turn": FinishReason.STOP,
    "stop_sequence": FinishReason.STOP,
    "max_tokens": FinishReason.LENGTH,
    "model_context_window_exceeded": FinishReason.LENGTH,
    "tool_use": FinishReason.TOOL_CALLS,
    "refusal": FinishReason.REFUSAL,
    "pause_turn": FinishReason.PAUSE_TURN,
}

#: Normalised tool-choice keywords mapped onto Anthropic's own vocabulary.
#: ``required`` is the ecosystem-neutral spelling of what Anthropic calls
#: ``any``; anything not listed here is treated as a tool name.
_TOOL_CHOICE_TYPES: dict[str, str] = {
    "auto": "auto",
    "any": "any",
    "required": "any",
    "none": "none",
}

#: Routes that mean "this endpoint does not implement token counting" rather
#: than "the request was wrong".
_ROUTE_ABSENT = frozenset({404, 405, 501})


@register_adapter
class AnthropicAdapter(Adapter):
    """Adapter for ``POST /v1/messages``."""

    name: ClassVar[str] = "anthropic"
    family: ClassVar[ApiFamily] = ApiFamily.ANTHROPIC
    default_base_url: ClassVar[str] = "https://api.anthropic.com/v1"
    default_auth_scheme: ClassVar[str] = "x-api-key"
    chat_path: ClassVar[str] = "/messages"
    capabilities: ClassVar[Capabilities] = Capabilities(
        # Confirmed two independent ways on 2026-07-26: the request schema has
        # no such fields, and no Anthropic model advertises either parameter in
        # OpenRouter's parameter vocabulary.
        logprobs=False,
        seed=False,
        tools=True,
        vision=True,
        structured_output=True,
        reasoning_effort=True,
        thinking_signature=True,
        count_tokens_endpoint=True,
        list_models_endpoint=True,
        streaming=True,
    )

    #: Value sent in the mandatory ``anthropic-version`` header. Overridable
    #: from ``ProviderConfig.headers``, because asking an endpoint for an older
    #: or bogus API version is a legitimate probe.
    api_version: ClassVar[str] = "2023-06-01"

    #: Separator used when several system messages are folded into the single
    #: ``system`` field. It affects token counts, so it is pinned rather than
    #: left to chance.
    system_separator: ClassVar[str] = "\n\n"

    def _auth_headers(self) -> dict[str, str]:
        headers = super()._auth_headers()
        if not any(key.lower() == "anthropic-version" for key in headers):
            headers["anthropic-version"] = self.api_version
        return headers

    # ------------------------------------------------------------------ request

    def build_payload(self, request: ChatRequest) -> dict[str, Any]:
        """Render a :class:`~llmverify.types.ChatRequest` as a Messages body.

        Optional fields are omitted rather than nulled, and ``extra_body`` is
        merged last and verbatim so that probes can send malformed or foreign
        parameters and observe how the endpoint objects.
        """
        turns, system = self._conversation(request.messages)

        payload: dict[str, Any] = {
            "model": self.config.model,
            "max_tokens": request.max_tokens,
            "messages": turns,
        }
        if system:
            payload["system"] = system

        for key, value in (("temperature", request.temperature), ("top_p", request.top_p)):
            if value is not None:
                payload[key] = value

        if request.stop:
            payload["stop_sequences"] = list(request.stop)

        if request.tools:
            payload["tools"] = [
                {
                    "name": tool.name,
                    "description": tool.description,
                    "input_schema": tool.parameters,
                }
                for tool in request.tools
            ]

        if request.tool_choice is not None:
            kind = _TOOL_CHOICE_TYPES.get(request.tool_choice)
            payload["tool_choice"] = (
                {"type": kind} if kind else {"type": "tool", "name": request.tool_choice}
            )

        # Both reasoning effort and structured output live under ``output_config``
        # as of the API reference read on 2026-07-26; the older top-level
        # ``output_format`` spelling is documented as transitional.
        output_config: dict[str, Any] = {}
        if request.reasoning_effort is not None:
            output_config["effort"] = request.reasoning_effort
        if request.response_schema is not None:
            output_config["format"] = {
                "type": "json_schema",
                "schema": request.response_schema,
            }
        if output_config:
            payload["output_config"] = output_config

        if request.thinking_budget is not None:
            payload["thinking"] = {"type": "enabled", "budget_tokens": request.thinking_budget}

        if request.stream:
            payload["stream"] = True

        # request.seed and request.logprobs are deliberately dropped: the
        # protocol has no such fields, and inventing a spelling for them would
        # destroy the api-surface probe's ability to tell a real Anthropic
        # endpoint (which rejects them) from a translating proxy (which does
        # not). A probe that wants them sent must say so through extra_body.
        payload.update(request.extra_body)
        return payload

    def _conversation(self, messages: tuple[Message, ...]) -> tuple[list[dict[str, Any]], str]:
        """Split messages into Anthropic turns and the top-level system prompt.

        Consecutive turns of the same role are folded together because the API
        requires user and assistant turns to alternate. Folding is also what
        puts several tool results into the single user turn that must answer a
        multi-tool assistant turn.
        """
        turns: list[dict[str, Any]] = []
        system_chunks: list[str] = []

        def add(role: str, blocks: list[dict[str, Any]]) -> None:
            if turns and turns[-1]["role"] == role:
                turns[-1]["content"].extend(blocks)
            else:
                turns.append({"role": role, "content": blocks})

        for message in messages:
            if message.role is Role.SYSTEM:
                text = message.text
                if text:
                    system_chunks.append(text)
            elif message.role is Role.TOOL:
                add("user", [_tool_result_block(message)])
            elif message.role is Role.ASSISTANT:
                add("assistant", _assistant_blocks(message))
            else:
                add("user", _content_blocks(message.content))

        for turn in turns:
            if not turn["content"]:
                # An empty turn is invalid, but so is silently dropping it: a
                # probe that sends one wants to see the endpoint's complaint.
                turn["content"] = [{"type": "text", "text": ""}]

        return turns, self.system_separator.join(system_chunks)

    # ----------------------------------------------------------------- response

    def parse_response(self, result: HttpResult) -> ChatResponse:
        """Normalise a non-streamed message, keeping the body intact in ``raw``.

        ``raw`` is the whole response, so identity-bearing fields that have no
        home in the normalised model -- ``service_tier``, ``inference_geo``,
        ``container`` -- remain available to probes.
        """
        body = result.json if isinstance(result.json, dict) else {}
        text, tool_calls, thinking = _split_blocks(body.get("content"))

        return ChatResponse(
            text=text,
            model_reported=_as_str(body.get("model")),
            # Genuine Anthropic ids are prefixed ``msg_``; the prefix is a cheap
            # family signature, so it is preserved rather than stripped.
            response_id=_as_str(body.get("id")),
            finish_reason=_stop_reason(body.get("stop_reason")),
            usage=_parse_usage(body.get("usage")),
            timing=Timing(total_s=result.total_s, ttft_s=result.ttft_s),
            tool_calls=tool_calls,
            thinking=thinking,
            raw=dict(body),
            http_status=result.status,
            http_headers=dict(result.headers),
            api_family=ApiFamily.ANTHROPIC,
        )

    def parse_stream(self, result: HttpResult) -> ChatResponse:
        """Reassemble a message from its event stream.

        The reconstructed content blocks are written back into ``raw`` in the
        same shape a non-streamed response would have, so a probe can read one
        or the other without caring which transport produced it. Signatures
        arrive as their own ``signature_delta`` frames and must be concatenated
        onto the thinking block they belong to, or replay would fail against a
        genuine endpoint.
        """
        blocks: dict[int, dict[str, Any]] = {}
        order: list[int] = []
        message: dict[str, Any] = {}
        usage: dict[str, Any] = {}
        stop_reason: Any = None
        stop_sequence: Any = None

        for event in result.events:
            kind = event.get("type")
            if kind == "message_start":
                start = event.get("message")
                if isinstance(start, dict):
                    message = dict(start)
                    if isinstance(start.get("usage"), dict):
                        usage.update(start["usage"])
            elif kind == "content_block_start":
                index = _block_index(event, order, starting=True)
                start_block = event.get("content_block")
                blocks[index] = _new_block(start_block if isinstance(start_block, dict) else {})
                if index not in order:
                    order.append(index)
            elif kind == "content_block_delta":
                index = _block_index(event, order)
                block = blocks.setdefault(index, _new_block({}))
                if index not in order:
                    order.append(index)
                _apply_delta(block, event.get("delta"))
            elif kind == "message_delta":
                delta = event.get("delta")
                if isinstance(delta, dict):
                    if delta.get("stop_reason") is not None:
                        stop_reason = delta["stop_reason"]
                    if delta.get("stop_sequence") is not None:
                        stop_sequence = delta["stop_sequence"]
                # Usage on message_delta is cumulative, so the last frame wins.
                if isinstance(event.get("usage"), dict):
                    usage.update(event["usage"])

        content = [_finish_block(blocks[i]) for i in order]
        text, tool_calls, thinking = _split_blocks(content)
        # message_start carries stop_reason: null, so message_delta is the real
        # source; the fallback only matters for a proxy that inverts that.
        final_stop = stop_reason if stop_reason is not None else message.get("stop_reason")

        raw = dict(message)
        raw["content"] = content
        raw["usage"] = usage
        if final_stop is not None:
            raw["stop_reason"] = final_stop
        if stop_sequence is not None:
            raw["stop_sequence"] = stop_sequence
        # Frame count is lost on reassembly, and a proxy that buffers a whole
        # completion into one frame looks nothing like token-by-token streaming.
        raw["_llmverify_stream_chunks"] = len(result.events)

        return ChatResponse(
            text=text,
            model_reported=_as_str(message.get("model")),
            response_id=_as_str(message.get("id")),
            finish_reason=_stop_reason(final_stop),
            usage=_parse_usage(usage),
            timing=Timing(total_s=result.total_s, ttft_s=result.ttft_s),
            tool_calls=tool_calls,
            thinking=thinking,
            raw=raw,
            http_status=result.status,
            http_headers=dict(result.headers),
            api_family=ApiFamily.ANTHROPIC,
        )

    # ----------------------------------------------------------------- optional

    async def count_tokens(
        self,
        messages: tuple[Message, ...],
        tools: tuple[ToolSpec, ...] = (),
        *,
        tool_choice: str | None = None,
    ) -> int:
        """Ask the endpoint how many input tokens these messages cost.

        This is the cleanest tokenizer fingerprint available anywhere: the call
        is free, has its own rate limit, runs the real tokenizer, and removes
        generation from the measurement entirely, so the number is a pure
        function of the prompt and the model's tool-use system prompt.

        ``tool_choice`` is exposed because Anthropic publishes *different*
        system-prompt overheads for auto/none versus any/tool, and the gap
        between the two is a second, independent reading of the same signal.

        The request is kept minimal on purpose -- no effort, no thinking budget
        -- so that the published overhead figures remain comparable.

        Raises :class:`~llmverify.errors.UnsupportedCapability` when the route
        does not exist or the response is not shaped as documented.
        """
        request = ChatRequest(messages=messages, tools=tools, tool_choice=tool_choice)
        payload = self.build_payload(request)
        payload.pop("max_tokens", None)
        payload.pop("stream", None)

        result = await self.http.request(
            "POST", f"{self.chat_path}/count_tokens", json_body=payload
        )
        if result.status in _ROUTE_ABSENT:
            raise UnsupportedCapability(
                f"{self.name} endpoint has no token counting route "
                f"({self.chat_path}/count_tokens returned HTTP {result.status})"
            )
        raise_for_status(result, context=f"{self.name} count tokens")

        body = result.json if isinstance(result.json, dict) else {}
        value = body.get("input_tokens")
        if isinstance(value, bool) or not isinstance(value, int):
            raise UnsupportedCapability(
                f"{self.name} count_tokens returned no integer input_tokens: {result.text[:200]!r}"
            )
        return value


